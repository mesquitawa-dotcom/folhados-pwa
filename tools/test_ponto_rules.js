'use strict';
const fs=require('fs'),assert=require('assert');
const {initializeTestEnvironment,assertSucceeds,assertFails}=require('@firebase/rules-unit-testing');
const {ref,set,get,update,remove,serverTimestamp}=require('firebase/database');
(async()=>{
 const env=await initializeTestEnvironment({projectId:'demo-fdo-rules',database:{rules:fs.readFileSync('database.rules.json','utf8')}});
 const pass=async(p,msg)=>{await assertSucceeds(p);console.log('OK  '+msg)};
 const deny=async(p,msg)=>{await assertFails(p);console.log('DENY '+msg)};
 try{
  await env.withSecurityRulesDisabled(async c=>{
   const db=c.database();
   await set(ref(db,'fdo_ponto_gerentes/gerente'),{ativo:true});
   await set(ref(db,'fdo_ponto_vinculos/emp1'),{funcionarioId:'jack',ativo:true});
   await set(ref(db,'fdo_ponto_vinculos/emp2'),{funcionarioId:'luana',ativo:true});
   await set(ref(db,'fdo_ponto_colaboradores/jack'),{nome:'Jacqueline',tipo:'mensalista',ativo:true});
   await set(ref(db,'fdo_ponto_colaboradores/luana'),{nome:'Luana',tipo:'horista',ativo:true});
   await set(ref(db,'fdo_ponto_financeiro/jack/2026-06-01~v1'),{centavos:230000,tipo:'mensalista'});
   await set(ref(db,'fdo_ponto_avisos_individuais/jack/x1'),{texto:'Somente Jacqueline'});
   await set(ref(db,'fdo_ponto_avisos_gerais/g1'),{texto:'Aviso geral'});
   await set(ref(db,'fdo_dispositivos/gerente'),{ativo:false});
  });
  const ger=env.authenticatedContext('gerente').database();
  const emp=env.authenticatedContext('emp1').database();
  const outro=env.authenticatedContext('emp2').database();
  const ext=env.authenticatedContext('desconhecido').database();
  await pass(get(ref(ger,'fdo_ponto_financeiro')),'gerência lê financeiro');
  await deny(get(ref(emp,'fdo_ponto_financeiro')),'funcionário não lê salários');
  await deny(get(ref(outro,'fdo_ponto_financeiro/jack')),'outro não lê salários');
  await pass(get(ref(emp,'fdo_ponto_colaboradores/jack')),'funcionário lê seu cadastro');
  await deny(get(ref(emp,'fdo_ponto_colaboradores/luana')),'funcionário não lê outro cadastro');
  await deny(get(ref(emp,'fdo_ponto_colaboradores')),'funcionário não lista equipe');
  await deny(get(ref(emp,'fdo_operadores')),'celular de ponto não lê operadores da produção');
  await deny(get(ref(emp,'fdo_v25/lotes')),'celular de ponto não lê produção');
  await pass(get(ref(emp,'fdo_ponto_avisos_individuais/jack')),'aviso individual do próprio funcionário');
  await deny(get(ref(outro,'fdo_ponto_avisos_individuais/jack')),'aviso individual oculto aos colegas');
  await pass(get(ref(emp,'fdo_ponto_avisos_gerais')),'aviso geral disponível');
  await deny(get(ref(ext,'fdo_ponto_avisos_gerais')),'aparelho não autorizado não vê avisos');
  await deny(set(ref(emp,'fdo_ponto_vinculos/emp1'),{funcionarioId:'luana',ativo:true}),'funcionário não pode autorizar a si próprio');
  await deny(set(ref(emp,'fdo_ponto_gerentes/emp1'),{ativo:true}),'funcionário não se torna gerente');
  await deny(set(ref(emp,'fdo_ponto_financeiro/jack/x'),{centavos:1}),'funcionário não altera salário');
  const mark={uid:'emp1',tipo:'entrada',clienteTs:Date.now(),servidorTs:serverTimestamp(),gps:{situacao:'dentro'},avaliacao:'normal',origem:'celular'};
  await pass(set(ref(emp,'fdo_ponto_marcacoes/jack/m1'),mark),'marca entrada própria');
  await deny(set(ref(emp,'fdo_ponto_marcacoes/jack/m1'),mark),'marcações são imutáveis');
  await deny(remove(ref(emp,'fdo_ponto_marcacoes/jack/m1')),'não apaga marcações');
  await deny(set(ref(emp,'fdo_ponto_marcacoes/luana/m2'),mark),'não registra ponto de colega');
  await deny(set(ref(emp,'fdo_ponto_marcacoes/jack/m3'),{...mark,avaliacao:'aprovado'}),'não se autoaprova');
  await pass(set(ref(emp,'fdo_ponto_marcacoes/jack/m4'),{...mark,avaliacao:'pendente',gps:{situacao:'fora',distancia:800}}),'permite ponto externo pendente');
  await pass(set(ref(ger,'fdo_ponto_aprovacoes/jack/m4/d1'),{decisao:'aprovado',motivo:'Conferido',gerenteUid:'gerente',servidorTs:serverTimestamp()}),'gerência aprova exceção');
  await deny(set(ref(emp,'fdo_ponto_aprovacoes/jack/m4/d2'),{decisao:'aprovado'}),'funcionário não aprova ponto');
  await deny(remove(ref(ger,'fdo_ponto_aprovacoes/jack/m4/d1')),'auditoria de decisão não pode ser apagada');
  await pass(set(ref(emp,'fdo_ponto_conferencias/jack/2026-06/c1'),{uid:'emp1',resumo:'abc123',clienteTs:Date.now(),servidorTs:serverTimestamp()}),'funcionário confirma seu mês');
  await deny(set(ref(emp,'fdo_ponto_conferencias/luana/2026-06/c2'),{uid:'emp1',resumo:'abc123',clienteTs:Date.now(),servidorTs:serverTimestamp()}),'não confirma ponto de colega');
  await pass(set(ref(ger,'fdo_ponto_financeiro/jack/2026-07-01~v1'),{centavos:240000,tipo:'mensalista',gerenteUid:'gerente',servidorTs:serverTimestamp()}),'gerente adiciona versão salarial');
  await deny(update(ref(ger,'fdo_ponto_financeiro/jack/2026-07-01~v1'),{centavos:1}),'versão salarial não é sobrescrita');
  await pass(get(ref(ger,'fdo_ponto_marcacoes')),'gerência consulta equipe');
  await deny(get(ref(ext,'fdo_ponto_marcacoes')),'desconhecido não vê marcações');
  await pass(set(ref(ger,'fdo_ponto_vinculos/emp1'),{funcionarioId:'jack',ativo:false}),'gerência revoga celular');
  await deny(get(ref(emp,'fdo_ponto_marcacoes/jack')),'revogação interrompe acesso');
  console.log('PONTO RULES OK — dados financeiros isolados, escopo pessoal, append-only e revogação');
 }finally{await env.cleanup()}
})().catch(e=>{console.error(e);process.exit(1)});
